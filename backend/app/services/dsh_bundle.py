"""按 DSH Cordis 插件标准生成可运行插件源码。

依据（来自本机 DSH 安装源码，非猜测）：
- references/host-plugin.md：bundle = package.json(dsh.bundle.patch) + cordis.patch.yml + locale + icon
- references/composition-reference.md：patch 行 id/name/config
- @deepseek-ai/dsh-system-prompt README：ctx.systemPrompt.section({name, order, text})
- references/practices.md：注册是 ctx.effect 拥有的；waterfall listener 非决策者返回 next()

behavior → DSH 扩展点映射：
- inject_system  → ctx.systemPrompt.section(静态提示词段落)
- memory_echo    → ctx.systemPrompt.section(动态 text 回调，注入会话记忆说明)
- intent_keywords→ ctx.systemPrompt.section(意图识别指引段落)
- compress_truncate → ctx.systemPrompt.section(上下文压缩指引段落)
- passthrough    → 仅 ctx.set 暴露元信息服务，不改动任何行为

所有生成插件均：
- 用 export function apply(ctx, config)
- 用 ctx.effect 注册并在卸载时清理
- 用 inject: ['system-prompt'] 声明依赖（无该服务时插件保持未激活，不抛错）
- 从 config 读取行为参数（用户在 cordis.patch.yml 中可覆盖）
"""
from __future__ import annotations

import json

BEHAVIOR_TO_DSL = {
    "inject_system": "prompt-section",
    "memory_echo": "memory-context",
    "intent_keywords": "intent-guidance",
    "compress_truncate": "context-compression",
    "passthrough": "passthrough",
}


def render_index_js(plugin) -> str:
    """生成真正符合 DSH 标准、可安装运行的 Cordis 插件入口。"""
    key = plugin.key
    name = (plugin.name or key).replace("'", "\\'")
    desc = (plugin.description or "").replace("'", "\\'")
    mech = (plugin.mechanism or "").replace("'", "\\'")
    behavior = (plugin.config or {}).get("behavior", "passthrough")
    cfg = plugin.config or {}
    section_text = ""
    if behavior == "inject_system":
        section_text = str(cfg.get("prompt", ""))
    elif behavior == "intent_keywords":
        rules = cfg.get("rules") or {}
        rules_json = json.dumps(rules, ensure_ascii=False)
        section_text = (
            "识别用户意图时优先参考以下关键词映射：" + rules_json +
            "。若命中检索类意图，先查询知识库再回答。"
        )
    elif behavior == "compress_truncate":
        section_text = (
            "回答前检查检索片段长度，超过上限的片段先截断，再写入上下文，避免超出窗口。"
            f"当前上限：{cfg.get('max_chars', 2000)} 字符。"
        )
    elif behavior == "memory_echo":
        section_text = "对话中记住用户明确陈述的关键信息，并在后续回复中保持一致。"
    if not section_text:
        section_text = desc or mech or f"{key} 插件已加载。"

    text_literal = json.dumps(section_text, ensure_ascii=False)
    return f"""// DSH Cordis plugin generated by Agent Work System
// key: {key}
// extension point: {plugin.extension_point}
// behavior: {behavior}
// This is a real, runnable DSH plugin: it contributes a system-prompt section.
const PLUGIN_KEY = {json.dumps(key)};
const SECTION_NAME = 'aws:' + PLUGIN_KEY;

export const inject = ['system-prompt'];

export function apply(ctx, config) {{
  const cfg = {{ ...{json.dumps(cfg, ensure_ascii=False)}, ...(config || {{}}) }};
  const sectionText = cfg.prompt || {text_literal};

  ctx.effect(() => {{
    // 系统提示词段落：这是 DSH 真实的扩展点（@deepseek-ai/dsh-system-prompt）
    const dispose = ctx.systemPrompt.section({{
      name: SECTION_NAME,
      order: 9000,
      text: sectionText,
    }});

    // 同时暴露插件元信息服务，便于其它插件/调试读取
    ctx.set('awsPlugin.' + PLUGIN_KEY, {{
      key: PLUGIN_KEY,
      name: {json.dumps(plugin.name or key, ensure_ascii=False)},
      description: {json.dumps(plugin.description or '', ensure_ascii=False)},
      mechanism: {json.dumps(plugin.mechanism or '', ensure_ascii=False)},
      extensionPoint: {json.dumps(plugin.extension_point, ensure_ascii=False)},
      behavior: {json.dumps(behavior)},
    }});

    return () => {{
      if (typeof dispose === 'function') dispose();
      ctx.remove('awsPlugin.' + PLUGIN_KEY);
    }};
  }});
}}
"""


def render_package_json(plugin) -> dict:
    """DSH bundle manifest（package.json）。"""
    bname = f"@local/aws-{plugin.key}"
    return {
        "name": bname,
        "version": plugin.version_str or "1.0.0",
        "private": True,
        "type": "module",
        "description": plugin.description or "",
        "exports": {
            ".": "./index.js",
            "./locale/*.json": "./locale/*.json",
        },
        "files": ["index.js", "cordis.patch.yml", "locale/*.json", "README.md"],
        "dsh": {"bundle": {"patch": "./cordis.patch.yml"}},
    }
